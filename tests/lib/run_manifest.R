# run_manifest.R: is a run folder evidence for the files it holds?
# (decision A-067; T1 review 2, reproducibility finding 1)
#
# As a library: source("tests/lib/run_manifest.R");
#   check_run_manifest(run, files, steps)
# stops with "run manifest: ..." unless all of these hold for the run folder
# `run` made by a runner that sources tests/lib/run_outputs.sh
# (tests/legacy/run_legacy_r.sh, run_legacy_python.sh, tests/regress_old.sh):
#   1. exit_status reads 0;
#   2. timings.tsv (step, seconds, exit) has exit 0 in every row and a row
#      for every tag in `steps`;
#   3. outputs_regenerated.sha256 lists every path of outputs_expected.txt
#      (no output is missing after the run);
#   4. every path in `files` (relative to `run`) is on that list, still has
#      the listed sha256, and is newer than outputs_expected.txt, which the
#      runner wrote after deleting the outputs and before the first step.
# A folder that only holds files at the committed paths (a copy of the
# committed tree, or a run whose step never wrote its output) fails 1, 3 or
# 4, before any content is compared. Returns `files` invisibly.

check_run_manifest <- function(run, files, steps) {
  f <- function(...) file.path(run, ...)
  need <- function(ok, ...) {
    if (!isTRUE(ok)) stop("run manifest: ", ..., call. = FALSE)
  }
  need(dir.exists(run), "not a folder: ", run)
  need(file.exists(f("exit_status")),
       "no exit_status in ", run, " (not a finished runner folder)")
  status <- readLines(f("exit_status"), warn = FALSE)
  need(identical(status, "0"), "exit_status is '",
       paste(status, collapse = " "), "', not 0")
  need(file.exists(f("timings.tsv")), "no timings.tsv in ", run)
  tm <- utils::read.delim(f("timings.tsv"), colClasses = "character")
  need(identical(names(tm), c("step", "seconds", "exit")),
       "timings.tsv must have the columns step, seconds, exit")
  failed <- tm$step[tm$exit != "0"]
  need(!length(failed), "steps with a non-zero exit: ",
       paste(failed, collapse = ", "))
  not_run <- setdiff(steps, tm$step)
  need(!length(not_run), "steps not run: ", paste(not_run, collapse = ", "))
  need(file.exists(f("outputs_expected.txt")) &&
         file.exists(f("outputs_regenerated.sha256")),
       "no outputs_expected.txt / outputs_regenerated.sha256 in ", run,
       " (outputs were not deleted before the run and listed after it)")
  expected <- readLines(f("outputs_expected.txt"), warn = FALSE)
  reg <- readLines(f("outputs_regenerated.sha256"), warn = FALSE)
  need(length(expected) > 0, "outputs_expected.txt is empty")
  need(all(grepl("^[0-9a-f]{64}  ", reg)),
       "outputs_regenerated.sha256 is not in sha256sum format")
  reg_sha <- substr(reg, 1, 64)
  reg_path <- substring(reg, 67)
  missing <- setdiff(expected, reg_path)
  need(!length(missing), "outputs missing after the run: ",
       paste(missing, collapse = ", "))
  start <- file.mtime(f("outputs_expected.txt"))
  for (p in files) {
    need(p %in% reg_path, "not regenerated by this run: ", p)
    need(file.exists(f(p)), "listed but missing now: ", p)
    sha <- digest::digest(file = f(p), algo = "sha256")
    need(identical(sha, reg_sha[[match(p, reg_path)]]),
         "changed after the run: ", p)
    need(file.mtime(f(p)) > start, "not newer than the start of the run: ", p)
  }
  invisible(files)
}
