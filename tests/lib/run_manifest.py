"""Is a run folder evidence for the files it holds? (decision A-067)

The Python twin of tests/lib/run_manifest.R (T1 review 2, reproducibility
finding 1). `check_run_manifest(run, files, steps)` raises ManifestError
unless the run folder, made by a runner that sources
tests/lib/run_outputs.sh, shows that:
  1. exit_status reads 0;
  2. timings.tsv (step, seconds, exit) has exit 0 in every row and a row
     for every tag in `steps`;
  3. outputs_regenerated.sha256 lists every path of outputs_expected.txt;
  4. every path in `files` (relative to the run folder) is on that list,
     still has the listed sha256, and is newer than outputs_expected.txt
     (written after the outputs were deleted, before the first step).
A folder that only holds files at the committed paths fails before any
content is compared.
"""

import csv
import hashlib
import re
from pathlib import Path

_SHA_LINE = re.compile(r'^([0-9a-f]{64})  (.+)$')


class ManifestError(AssertionError):
    """The run folder does not prove that the files are its outputs."""


def _need(ok, message):
    if not ok:
        raise ManifestError(f'run manifest: {message}')


def _sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def check_run_manifest(run, files, steps=()):
    """Raise ManifestError unless `files` were written by the run `run`."""
    run = Path(run)
    _need(run.is_dir(), f'not a folder: {run}')
    status = run / 'exit_status'
    _need(status.is_file(),
          f'no exit_status in {run} (not a finished runner folder)')
    text = status.read_text().splitlines()
    _need(text == ['0'], f'exit_status is {text!r}, not 0')
    timings = run / 'timings.tsv'
    _need(timings.is_file(), f'no timings.tsv in {run}')
    with open(timings, newline='') as f:
        reader = csv.DictReader(f, delimiter='\t')
        _need(reader.fieldnames == ['step', 'seconds', 'exit'],
              'timings.tsv must have the columns step, seconds, exit')
        rows = list(reader)
    failed = [r['step'] for r in rows if r['exit'] != '0']
    _need(not failed, f'steps with a non-zero exit: {", ".join(failed)}')
    not_run = [s for s in steps if s not in {r['step'] for r in rows}]
    _need(not not_run, f'steps not run: {", ".join(not_run)}')
    expected_path = run / 'outputs_expected.txt'
    regenerated_path = run / 'outputs_regenerated.sha256'
    _need(expected_path.is_file() and regenerated_path.is_file(),
          f'no outputs_expected.txt / outputs_regenerated.sha256 in {run} '
          '(outputs were not deleted before the run and listed after it)')
    expected = expected_path.read_text().splitlines()
    _need(expected, 'outputs_expected.txt is empty')
    listed = {}
    for line in regenerated_path.read_text().splitlines():
        m = _SHA_LINE.match(line)
        _need(m, 'outputs_regenerated.sha256 is not in sha256sum format')
        listed[m.group(2)] = m.group(1)
    missing = [p for p in expected if p not in listed]
    _need(not missing, f'outputs missing after the run: {", ".join(missing)}')
    start = expected_path.stat().st_mtime_ns
    for p in files:
        _need(p in listed, f'not regenerated by this run: {p}')
        path = run / p
        _need(path.is_file(), f'listed but missing now: {p}')
        _need(_sha256(path) == listed[p], f'changed after the run: {p}')
        _need(path.stat().st_mtime_ns > start,
              f'not newer than the start of the run: {p}')
    return list(files)
