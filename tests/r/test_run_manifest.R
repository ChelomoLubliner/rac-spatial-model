same <- vapply(c(step1, step2), function(f) {
  identical(digest::digest(file = file.path(stale, "repo", f),
                           algo = "sha256"), b_sha[[f]])
}, logical(1))
tb <- readRDS(p("tests", "baseline", "local", "models_local.rds"))
