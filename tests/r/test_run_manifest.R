           "CML equals Tier B: content checks alone cannot tell"))

live_check <- function(run) {
  rscript <- file.path(R.home("bin"), "Rscript")
  out <- suppressWarnings(system2(
    rscript, shQuote(p("tests", "r", "test_old_regression.R")),
    stdout = TRUE, stderr = TRUE, env = paste0("RAC_REGRESS_R_RUN=", run)))
  s <- attr(out, "status")
  list(status = if (is.null(s)) 0L else s, out = out)
}
r1 <- live_check(stale)
stopifnot(r1$status != 0,
          any(grepl("run manifest: no exit_status", r1$out, fixed = TRUE)),
          !any(grepl("live rerun", r1$out, fixed = TRUE)),
          !any(grepl("ALL PASS", r1$out, fixed = TRUE)))
pass("test_old_regression.R fails on the stale folder: no exit_status")

writeLines("0", file.path(stale, "exit_status"))
writeLines(c("step\tseconds\texit",
             paste0(c("step1", "step2", "step3_glmm", "step3_cml"),
                    "\t1\t0")), file.path(stale, "timings.tsv"))
r2 <- live_check(stale)
stopifnot(r2$status != 0,
          any(grepl("run manifest: no outputs_expected.txt", r2$out,
                    fixed = TRUE)),
          !any(grepl("live rerun", r2$out, fixed = TRUE)))
pass(paste("with a forged exit_status 0 and timings.tsv it still fails: the",
           "outputs were never deleted and listed"))
cat("ALL PASS test_run_manifest\n")
