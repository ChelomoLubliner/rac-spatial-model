# Run from anywhere: Rscript tests/r/test_run_manifest.R
#  1. check_run_manifest() on run folders written by tests/lib/run_outputs.sh:
#     a finished run passes; a failed or missing step, a missing, unlisted,
#     changed or old output is refused.
#  2. The negative test the review asked for: a folder shaped like the
#     reviewer's <scratch>/rv2_t1/fake_stale_zv7m57 (the committed step-1
#     CSVs with CR removed, the committed step-2 CSVs, CML and GLMM, and
#     nothing else). Its five CSVs equal Tier B byte for byte and its CML
#     equals Tier B, so the old live check printed "ALL PASS" for such a
#     folder (with the reviewer's WSL GLMM) although no step had run.
#     test_old_regression.R must now fail on it, at the manifest, before any
#     content is compared; also when exit_status and timings.tsv are forged.
# Writes only to R's session temp folder.
suppressMessages(library(survival))
root <- local({
  f <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
  normalizePath(file.path(dirname(f), "..", ".."))
})
source(file.path(root, "tests", "lib", "run_manifest.R"))
p <- function(...) file.path(root, ...)
pass <- function(name) cat("PASS", name, "\n")
error_of <- function(expr) {
  tryCatch({
    expr
    "no error"
  }, error = function(e) conditionMessage(e))
}
outputs_lib <- p("tests", "lib", "run_outputs.sh")
outs <- c("repo/data/a.csv", "repo/models/m.rds")

bash <- function(script, ...) {
  out <- suppressWarnings(system2("bash", c("-c", shQuote(paste0(
    "set -euo pipefail; source ", shQuote(outputs_lib), "; ", script)),
    "bash", shQuote(c(...))), stdout = TRUE, stderr = TRUE))
  s <- attr(out, "status")
  if (is.null(s)) 0L else s
}
old_time <- as.POSIXct("2020-09-13 12:26:40", tz = "UTC")

# A run folder in the shape a runner leaves: committed files at the output
# paths, then begin (delete + list), the steps write, end (hash + list).
finished_run <- function(write = outs, exit = "0",
                         steps = c("step1", "step2")) {
  run <- tempfile("run_")
  for (f in c(outs, "repo/data/input.csv")) {
    dir.create(dirname(file.path(run, f)), recursive = TRUE,
               showWarnings = FALSE)
    writeLines(paste("committed", f), file.path(run, f))
    Sys.setFileTime(file.path(run, f), old_time)
  }
  stopifnot(bash('rac_outputs_begin "$1" "${@:2}"', run, outs) == 0)
  for (f in write) writeLines(paste("regenerated", f), file.path(run, f))
  end <- bash('rac_outputs_end "$1"', run)
  writeLines(c("step\tseconds\texit", paste0(steps, "\t1.5\t", exit)),
             file.path(run, "timings.tsv"))
  writeLines(if (end == 0) exit else "1", file.path(run, "exit_status"))
  run
}

# 1. check_run_manifest()
good <- finished_run()
stopifnot(identical(check_run_manifest(good, outs, "step2"), outs))
pass("a finished run passes: both outputs regenerated, steps exit 0")

expect_refusal <- function(run, pattern, files = outs, steps = "step1") {
  e <- error_of(check_run_manifest(run, files, steps))
  if (!grepl(pattern, e, fixed = TRUE)) {
    stop(sprintf("expected '%s', got '%s'", pattern, e))
  }
}
failed <- finished_run(exit = "1")
expect_refusal(failed, "exit_status is '1', not 0")
writeLines("0", file.path(failed, "exit_status"))
expect_refusal(failed, "steps with a non-zero exit: step1, step2")
expect_refusal(finished_run(steps = "step2"), "steps not run: step1")
partial <- finished_run(write = outs[1])
stopifnot(readLines(file.path(partial, "exit_status")) == "1")
writeLines("0", file.path(partial, "exit_status"))
expect_refusal(partial, "outputs missing after the run: repo/models/m.rds")
expect_refusal(good, "not regenerated by this run: repo/data/input.csv",
               files = "repo/data/input.csv")
changed <- finished_run()
writeLines("replaced after the run", file.path(changed, outs[2]))
expect_refusal(changed, "changed after the run: repo/models/m.rds")
old <- finished_run()
Sys.setFileTime(file.path(old, outs[1]), old_time)
expect_refusal(old, "not newer than the start of the run: repo/data/a.csv")
pass(paste("refused: exit_status 1, a step with exit 1, a step not run, an",
           "output missing, a file not on the list, changed, or older than",
           "the start"))

# 2. The stale folder of the review, rebuilt from the committed files.
stale <- tempfile("fake_stale_")
copy_into <- function(rel, strip_cr = FALSE) {
  dest <- file.path(stale, "repo", rel)
  dir.create(dirname(dest), recursive = TRUE, showWarnings = FALSE)
  x <- readBin(p(rel), "raw", file.size(p(rel)))
  if (strip_cr) x <- x[x != as.raw(13)]
  writeBin(x, dest)
}
step1 <- c("data/all_cont.csv", "processed_data/dataCC.csv",
           "processed_data/shoe_pixel_counts.csv")
step2 <- c("processed_data/dataCC_distance_temp.csv",
           "processed_data/dataCC_distance.csv")
for (f in step1) copy_into(f, strip_cr = TRUE)
for (f in c(step2, "saved_models/CML_MODEL.rds",
            "saved_models/NEW_X_NS_XY.rds")) copy_into(f)

tier_b <- readLines(p("tests", "baseline", "local", "r_outputs.sha256"))
